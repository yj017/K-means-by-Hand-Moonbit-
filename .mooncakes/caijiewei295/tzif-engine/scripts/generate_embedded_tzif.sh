#!/usr/bin/env bash
# Generate a compile-time MoonBit Bytes literal from one audited TZif file.
#
# Usage:
#   scripts/generate_embedded_tzif.sh INPUT.tzif TZDB_RELEASE OUTPUT.mbt SYMBOL
#
# Example:
#   scripts/generate_embedded_tzif.sh \
#     /usr/share/zoneinfo/America/New_York 2026b \
#     golden/america_new_york_2026b.mbt america_new_york_2026b

set -euo pipefail

if [ "$#" -ne 4 ]; then
  echo "usage: $0 INPUT.tzif TZDB_RELEASE OUTPUT.mbt SYMBOL" >&2
  exit 64
fi

tzif_source=$1
tzdb_release=$2
output_file=$3
symbol=$4

if [ ! -f "$tzif_source" ]; then
  echo "error: TZif source is not a regular file: $tzif_source" >&2
  exit 66
fi

case "$symbol" in
  ''|*[!A-Za-z0-9_]*|[0-9]*)
    echo "error: SYMBOL must be a MoonBit identifier" >&2
    exit 64
    ;;
esac

if command -v sha256sum >/dev/null 2>&1; then
  source_sha256=$(sha256sum "$tzif_source" | awk '{print $1}')
else
  source_sha256=$(shasum -a 256 "$tzif_source" | awk '{print $1}')
fi
source_bytes=$(wc -c < "$tzif_source" | tr -d '[:space:]')

{
  printf '%s\n' "// Generated by scripts/generate_embedded_tzif.sh; do not hand-edit bytes."
  printf '%s\n' "// Source file: $tzif_source"
  printf '%s\n' "// TZDB release: $tzdb_release"
  printf '%s\n' "// Source SHA-256: $source_sha256"
  printf '%s\n\n' "// Source length: $source_bytes bytes"
  printf '%s\n' '///|'
  printf '%s\n' "pub let ${symbol}_tzdb_release = \"$tzdb_release\""
  printf '%s\n\n' '///|'
  printf '%s\n' "pub let ${symbol}_sha256 = \"$source_sha256\""
  printf '%s\n\n' '///|'
  printf '%s\n' "pub let ${symbol}_byte_length = $source_bytes"
  printf '%s\n\n' '///|'
  printf '%s\n' "pub let $symbol : Bytes = ["
  od -An -v -t x1 "$tzif_source" | awk '{
    printf "  "
    for (i = 1; i <= NF; i = i + 1) {
      printf "b%c\\x%s%c, ", 39, $i, 39
    }
    printf "\n"
  }'
  printf '%s\n' ']'
} > "$output_file"

echo "generated $output_file from $tzif_source ($source_bytes bytes, sha256 $source_sha256)"
